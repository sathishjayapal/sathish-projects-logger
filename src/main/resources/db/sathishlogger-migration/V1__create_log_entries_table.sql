CREATE TABLE log_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_name   VARCHAR(255)  NOT NULL,
    correlation_id     VARCHAR(255),
    log_level          VARCHAR(255)  NOT NULL,
    message            VARCHAR(4000) NOT NULL,
    logger_name        VARCHAR(255),
    thread_name        VARCHAR(255),
    exception_message  VARCHAR(2000),
    stack_trace        VARCHAR(8000),
    timestamp          TIMESTAMP     NOT NULL
);

CREATE TABLE log_entry_metadata (
    log_entry_id    BIGINT       NOT NULL REFERENCES log_entries (id),
    metadata_key    VARCHAR(255) NOT NULL,
    metadata_value  VARCHAR(255),
    PRIMARY KEY (log_entry_id, metadata_key)
);

CREATE INDEX idx_log_entries_application_name ON log_entries (application_name);
CREATE INDEX idx_log_entries_correlation_id ON log_entries (correlation_id);
CREATE INDEX idx_log_entries_log_level ON log_entries (log_level);
CREATE INDEX idx_log_entries_timestamp ON log_entries (timestamp);
CREATE INDEX idx_log_entries_app_timestamp ON log_entries (application_name, timestamp);
